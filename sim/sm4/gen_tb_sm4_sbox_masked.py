#!/usr/bin/env python3
"""gen_tb_sm4_sbox_masked.py -- 从权威 S 盒生成 sm4_sbox_masked testbench。

铁律：TB 单一来源，S 盒由 sm4_engine_sys.v 正则解析生成。
"""
import re
from pathlib import Path

ROOT = Path(r"C:/Users/Yi/WorkBuddy/2026-10-02-09-55-51/fpga-guomi-crypto")
SRC = ROOT / "rtl" / "sm4" / "sm4_engine_sys.v"
DST = ROOT / "sim" / "sm4" / "tb_sm4_sbox_masked.v"

body = SRC.read_text(encoding="utf-8")
pairs = re.findall(r"8'h([0-9a-fA-F]{2})\s*:\s*sm4_sbox\s*=\s*8'h([0-9a-fA-F]{2})", body)
assert len(pairs) == 256, f"expect 256, got {len(pairs)}"

# 生成 TB
tb = []
tb.append("`timescale 1ns / 1ps")
tb.append("")
tb.append("// =============================================================================")
tb.append("// tb_sm4_sbox_masked.v -- 自动生成")
tb.append("// 生成脚本: sim/sm4/gen_tb_sm4_sbox_masked.py")
tb.append("// 权威 S 盒来源: rtl/sm4/sm4_engine_sys.v")
tb.append("// 铁律: TB 单一来源；改 S 盒 -> 重跑本脚本")
tb.append("// =============================================================================")
tb.append("")
tb.append("module tb_sm4_sbox_masked;")
tb.append("")
tb.append("    // =========================================================================")
tb.append("    // 1. 权威 S 盒表（从 sm4_engine_sys.v 正则解析）")
tb.append("    // =========================================================================")
tb.append("    reg [7:0] S_EXPECTED [0:255];")
tb.append("")
tb.append("    initial begin")
for a, b in pairs:
    tb.append(f"        S_EXPECTED[{int(a,16):3d}] = 8'h{b};")
tb.append("    end")
tb.append("")
tb.append("    // =========================================================================")
tb.append("    // 2. DUT signals")
tb.append("    // =========================================================================")
tb.append("    reg         clk = 1'b0;")
tb.append("    reg         rst_n = 1'b1;")
tb.append("    reg  [7:0]  x       = 8'h00;")
tb.append("    reg  [7:0]  trng_data = 8'h00;")
tb.append("    reg         trng_valid = 1'b0;")
tb.append("    wire [7:0]  y;")
tb.append("")
tb.append("    integer pass_cnt = 0;")
tb.append("    integer fail_cnt = 0;")
tb.append("    reg seen_y3 [0:255];   // T3 均匀性检查")
tb.append("")
tb.append("    // =========================================================================")
tb.append("    // 3. DUT 例化：3 组 —— 掩码关闭 / 掩码开启 / 掩码开但 trng_valid=0")
tb.append("    // =========================================================================")
tb.append("")
tb.append("    // DUT-A: 掩码关闭 (sm4_sbox_masked_en = 0) —— 透传 S(x)")
tb.append("    sm4_sbox_masked #(.sm4_sbox_masked_en(1'b0)) dut_a (")
tb.append("        .clk(clk), .rst_n(rst_n), .x(x), .trng_data(trng_data),")
tb.append("        .trng_valid(trng_valid), .y(y_a)")
tb.append("    );")
tb.append("    wire [7:0] y_a;")
tb.append("")
tb.append("    // DUT-B: 掩码开启，trng_valid=1 —— y = S(x) ^ trng_data")
tb.append("    sm4_sbox_masked #(.sm4_sbox_masked_en(1'b1)) dut_b (")
tb.append("        .clk(clk), .rst_n(rst_n), .x(x), .trng_data(trng_data),")
tb.append("        .trng_valid(1'b1), .y(y_b)")
tb.append("    );")
tb.append("    wire [7:0] y_b;")
tb.append("")
tb.append("    // DUT-C: 掩码开启但 trng_valid=0 —— 退化为 S(x)")
tb.append("    sm4_sbox_masked #(.sm4_sbox_masked_en(1'b1)) dut_c (")
tb.append("        .clk(clk), .rst_n(rst_n), .x(x), .trng_data(trng_data),")
tb.append("        .trng_valid(1'b0), .y(y_c)")
tb.append("    );")
tb.append("    wire [7:0] y_c;")
tb.append("")
tb.append("    // =========================================================================")
tb.append("    // 4. 测试序列")
tb.append("    // =========================================================================")
tb.append("    initial begin")
tb.append("        $display(\"==================== sm4_sbox_masked TB ===================\");")
tb.append("        $display(\"权威 S 盒条目数: 256\");")
tb.append("        $display(\"S[0]=%h S[1]=%h S[4]=%h S[128]=%h\", S_EXPECTED[0], S_EXPECTED[1], S_EXPECTED[4], S_EXPECTED[128]);")
tb.append("")
tb.append("        // 复位")
tb.append("        rst_n = 1'b0;")
tb.append("        #5;")
tb.append("        rst_n = 1'b1;")
tb.append("        #5;")
tb.append("")
tb.append("        // ---------------------------------------------------------------------")
tb.append("        // T1: 掩码关闭 —— y_a 必须逐点等于 S_EXPECTED[x] (256/256)")
tb.append("        // ---------------------------------------------------------------------")
tb.append("        trng_valid = 1'b0;   // 掩码关闭下 trng_valid 也应无关")
tb.append("        trng_data  = 8'h00;")
tb.append("        $display(\"\\n[T1] Mask DISABLED: 256/256 y_a == S_EXPECTED\");")
tb.append("        for (integer i = 0; i < 256; i = i + 1) begin")
tb.append("            x = i[7:0];")
tb.append("            #2;")
tb.append("            if (y_a != S_EXPECTED[i]) begin")
tb.append("                $display(\"  FAIL x=%02d y_a=%h expected=%h\", i, y_a, S_EXPECTED[i]);")
tb.append("                fail_cnt = fail_cnt + 1;")
tb.append("            end else begin")
tb.append("                pass_cnt = pass_cnt + 1;")
tb.append("            end")
tb.append("        end")
tb.append("")
tb.append("        // ---------------------------------------------------------------------")
tb.append("        // T2: 掩码开启 + trng_valid=1 —— y_b ^ trng_data == S_EXPECTED")
tb.append("        //     注意：因 y 为组合信号，需采样 #1 越 NBA")
tb.append("        // ---------------------------------------------------------------------")
tb.append("        trng_valid = 1'b1;")
tb.append("        $display(\"\\n[T2] Mask ENABLED, trng_valid=1: y_b ^ trng_data == S_EXPECTED\");")
tb.append("        // 用 4 组不同 trng_data 值")
tb.append("        trng_data = 8'hAA; #1;")
tb.append("        for (integer i = 0; i < 256; i = i + 1) begin")
tb.append("            x = i[7:0];")
tb.append("            #2;")
tb.append("            #1;   // 越 NBA 采样（DUT 纯组合，无需 clk）")
tb.append("            if ((y_b ^ trng_data) != S_EXPECTED[i]) begin")
tb.append("                if (fail_cnt < 5) $display(\"  FAIL T2 trng=AA x=%02d y_b=%h trng=%h got=%h expected=%h\",")
tb.append("                    i, y_b, trng_data, y_b ^ trng_data, S_EXPECTED[i]);")
tb.append("                fail_cnt = fail_cnt + 1;")
tb.append("            end else begin")
tb.append("                pass_cnt = pass_cnt + 1;")
tb.append("            end")
tb.append("        end")
tb.append("")
tb.append("        // T2b: trng_data=0x5A 再验一次")
tb.append("        trng_data = 8'h5A; #1;")
tb.append("        for (integer i = 0; i < 256; i = i + 1) begin")
tb.append("            x = i[7:0];")
tb.append("            #2;")
tb.append("            #1;")
tb.append("            if ((y_b ^ trng_data) != S_EXPECTED[i]) begin")
tb.append("                if (fail_cnt < 5) $display(\"  FAIL T2b trng=5A x=%02d y_b=%h got=%h expected=%h\",")
tb.append("                    i, y_b, y_b ^ trng_data, S_EXPECTED[i]);")
tb.append("                fail_cnt = fail_cnt + 1;")
tb.append("            end else begin")
tb.append("                pass_cnt = pass_cnt + 1;")
tb.append("            end")
tb.append("        end")
tb.append("")
tb.append("        // T2c: trng_data=0x00 —— 应等于 S(x)（掩码为 0 时退化）")
tb.append("        trng_data = 8'h00; #1;")
tb.append("        for (integer i = 0; i < 256; i = i + 1) begin")
tb.append("            x = i[7:0];")
tb.append("            #2;")
tb.append("            #1;")
tb.append("            if (y_b != S_EXPECTED[i]) begin")
tb.append("                if (fail_cnt < 5) $display(\"  FAIL T2c trng=00 x=%02d y_b=%h expected=%h\",")
tb.append("                    i, y_b, S_EXPECTED[i]);")
tb.append("                fail_cnt = fail_cnt + 1;")
tb.append("            end else begin")
tb.append("                pass_cnt = pass_cnt + 1;")
tb.append("            end")
tb.append("        end")
tb.append("")
tb.append("        // ---------------------------------------------------------------------")
tb.append("        // T3: 掩码开启 + trng_valid=0 —— 退化为 S(x)")
tb.append("        // ---------------------------------------------------------------------")
tb.append("        $display(\"\\n[T3] Mask ENABLED but trng_valid=0: y_c == S_EXPECTED\");")
tb.append("        for (integer i = 0; i < 256; i = i + 1) begin")
tb.append("            x = i[7:0];")
tb.append("            trng_data = 8'hFF;   // 无关，应被 trng_valid 屏蔽")
tb.append("            #2;")
tb.append("            #1;")
tb.append("            if (y_c !== S_EXPECTED[i]) begin")
tb.append("                if (fail_cnt < 5) $display(\"  FAIL T3 x=%02d y_c=%h expected=%h\",")
tb.append("                    i, y_c, S_EXPECTED[i]);")
tb.append("                fail_cnt = fail_cnt + 1;")
tb.append("            end else begin")
tb.append("                pass_cnt = pass_cnt + 1;")
tb.append("            end")
tb.append("        end")
tb.append("")
tb.append("        // ---------------------------------------------------------------------")
tb.append("        // T3b: 均匀性 —— 固定 x=0, 遍历 trng_data, y_b 覆盖 0..255 各一次")
tb.append("        //      (份额均匀性直接检查；因 S 双射 + XOR 保双射)")
tb.append("        // ---------------------------------------------------------------------")
tb.append("        $display(\"\\n[T3b] Uniformity: fixed x=0, scan trng_data, y_b covers 0..255 once\");")
tb.append("        trng_valid = 1'b1;")
tb.append("        x = 8'h00;")
tb.append("        for (integer k = 0; k < 256; k = k + 1) seen_y3[k] = 0;")
tb.append("        for (integer t = 0; t < 256; t = t + 1) begin")
tb.append("            trng_data = t[7:0];")
tb.append("            #1;")
tb.append("            if (seen_y3[y_b] != 0) begin")
tb.append("                if (fail_cnt < 5) $display(\"  FAIL T3 trng=%02h y_b=%h (duplicate)\", t, y_b);")
tb.append("                fail_cnt = fail_cnt + 1;")
tb.append("            end else begin")
tb.append("                seen_y3[y_b] = 1;")
tb.append("                pass_cnt = pass_cnt + 1;")
tb.append("            end")
tb.append("        end")
tb.append("")
tb.append("        // ---------------------------------------------------------------------")
tb.append("        // T4: 交叉验证 —— y_a (关闭) 与 y_c (开启但 valid=0) 一致")
tb.append("        $display(\"\\n[T4] Cross-check: y_a (disabled) == y_c (enabled, valid=0)\");")
tb.append("        trng_valid = 1'b0;")
tb.append("        for (integer i = 0; i < 256; i = i + 1) begin")
tb.append("            x = i[7:0];")
tb.append("            #2;")
tb.append("            #1;")
tb.append("            if (y_a != y_c) begin")
tb.append("                if (fail_cnt < 5) $display(\"  FAIL T4 x=%02d y_a=%h y_c=%h\", i, y_a, y_c);")
tb.append("                fail_cnt = fail_cnt + 1;")
tb.append("            end else begin")
tb.append("                pass_cnt = pass_cnt + 1;")
tb.append("            end")
tb.append("        end")
tb.append("")
tb.append("        // =========================================================================")
tb.append("        // 汇总")
tb.append("        // =========================================================================")
tb.append("        $display(\"\\n==================== RESULTS ====================\");")
tb.append("        $display(\"PASS: %0d\", pass_cnt);")
tb.append("        $display(\"FAIL: %0d\", fail_cnt);")
tb.append("        if (fail_cnt == 0) begin")
tb.append("            $display(\"ALL TESTS PASSED\");")
tb.append("        end else begin")
tb.append("            $display(\"SOME TESTS FAILED\");")
tb.append("            $fatal(1);")
tb.append("        end")
tb.append("    end")
tb.append("")
tb.append("endmodule")

DST.write_text("\n".join(tb), encoding="utf-8")
print(f"OK: wrote {DST}")
print(f"TB 权威 S 盒条目: {len(pairs)}")
