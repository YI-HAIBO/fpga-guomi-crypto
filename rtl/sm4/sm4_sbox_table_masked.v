// =============================================================================
// sm4_sbox_table_masked.v -- SM4 S 盒表掩码查询 (C1 升级 B-2)
// =============================================================================
// 版本: 1.0
// 日期: 2026-10-05
// 设计: 齐流晶 (FPGA Full-Flow Lead)
// 关联: docs/Phase0_5_C1_升级路线选择_v1.md §7 (B-2)
// 参考模型: sim/sm4/ref_sm4_sbox_table_masked.py (B-1, ALL PASS)
// =============================================================================
//
// 【设计目标】
//   路线 B（掩码表重计算 RSM-LUT）的 S 盒级实现。
//   每次加密/轮前用新随机掩码重生成 256 项掩码表，查询时仅输出掩码值，
//   消码由消费者端 XOR r_table[x^c] 完成。
//
// 【接口】
//   本模块为**纯组合查询**，r_table 和 c 由外部（B-3 引擎级）提供。
//   刷新逻辑（生成新 c 和 r_table）在 B-3 中实现。
//
// 【安全边界】
//   +-----------------------------+-----------------------------------------+
//   | Threat                      | Resistance                              |
//   +-----------------------------+-----------------------------------------+
//   | 单点静态探测（S 盒输出总线） | Resistant (y = S(x)^r_table[x^c])      |
//   | SPA 对最终密文              | Resistant (每轮独立掩码)                |
//   | 1-order TVLA（仅查询阶段）  | Resistant（"刷新不被探测"假设下）       |
//   | 联合动态（同时观测 y 与 r） | NOT resistant (S(x)=y^r_table[x^c])    |
//   | 毛刺                        | NOT resistant (表刷新过程可见)          |
//   +-----------------------------+-----------------------------------------+
//
// 【与 C1-2 MVP 的区别】
//   C1-2: y = S(x) ^ r_out（r_out 是单 8-bit 随机数，全局共用）
//   B-2:  y = S(x) ^ r_table[x^c]（r_table 是 256 项独立随机表，
//         c 是 8-bit 常量掩码，两者每轮独立刷新）
//   B-2 的优势：掩码粒度从"全局 1 个随机数"提升到"256 项独立随机 + 1 个常量"，
//   攻击者无法通过多次观测 y 来消除掩码（因为每次查询对应不同 r_table 条目）。
//
// 【已知安全边界（明确不抵御）】
//   联合动态探测：若攻击者同时观测 y 与 r_table（或能推算 r_table[x^c]），
//   仍可直接算出 S(x) = y ^ r_table[x^c]。
//   严格 1-order 需假设"刷新过程不被探测"（标准 RSM-LUT 假设）。
//   毛刺安全需额外刷新随机化（B-3 实现）。
//
// 【面积估算】
//   - sm4_sbox_raw 例化: ~100 LUT
//   - r_table 选择器 (256:1): ~200 LUT
//   - XOR + 多路选择: ~50 LUT
//   - 总增量: ~350 LUT（相对 sm4_sbox_raw 的 ~100 LUT）
//
// 【时序】
//   纯组合路径：x -> (x^c) -> r_table 选择 -> XOR -> y
//   关键路径: ~3-5 ns @ 100 MHz（xc7a200t 综合后估算）
//   如需时序优化，可将 r_table 存储改为 BRAM（延迟 +1 cycle）
// =============================================================================

`timescale 1ns / 1ps

module sm4_sbox_table_masked #(
    parameter masked_en_default = 1'b0   // 掩码开关默认值（0=透传，1=掩码）
)(
    input  wire        clk,              // 时钟（仅用于同步信号，本模块组合逻辑不使用）
    input  wire        rst_n,            // 异步低有效复位（仅用于同步信号）
    input  wire        masked_en,        // 掩码开关（1=启用掩码，0=透传）
    input  wire [7:0]  x,                // 8-bit S 盒输入
    input  wire [7:0]  c,                // 8-bit 常量掩码（本轮）
    input  wire [256*8-1:0] r_table,     // 256 x 8-bit 掩码表（本轮，独立随机）
    output wire [7:0]  y                 // 8-bit 输出 = S(x) ^ r_table[x^c]
);

    // =========================================================================
    // 1. 未掩码 S 盒查询（例化独立 module sm4_sbox_raw）
    // =========================================================================
    wire [7:0] s_true;
    sm4_sbox_raw u_sbox_raw (.x(x), .y(s_true));

    // =========================================================================
    // 2. 掩码索引：idx = x ^ c
    // =========================================================================
    wire [7:0] idx = x ^ c;

    // =========================================================================
    // 3. 掩码表条目选择：r_val = r_table[idx]
    //    使用移位法避免 variable part-select 在 iverilog 中的兼容性问题
    //    r_table >> (idx * 8) 后取低 8 位
    // =========================================================================
    // ⚠ 2026-10-06: 与 sm4_engine_masked_v2 同源踩坑。
    //   原来 `r_table >> (idx * 8)` 对 2048 位向量做变量移位 -> 桶形移位器
    //   (~11 x 2048 = 22528 LUT)。等价改成变量 part-select, 综合成一个
    //   2048:8 选择器。idx*8 最大 2040, +7 = 2047, 不越界。
    wire [10:0] r_byte_addr = {idx, 3'b000};
    wire [7:0]  r_val       = r_table[r_byte_addr +: 8];

    // =========================================================================
    // 4. 掩码输出：y = S(x) ^ r_table[x^c]
    //    掩码关闭时透传 S(x)
    // =========================================================================
    assign y = masked_en ? (s_true ^ r_val) : s_true;

endmodule
